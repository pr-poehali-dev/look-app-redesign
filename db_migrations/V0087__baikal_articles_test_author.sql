Когда ехать

Лучшее время — с середины июля до конца августа. Вода у берега прогревается до 15–20 градусов только в мелких заливах, в открытом озере она холодная даже в жару. Июнь свежий и малолюдный, в начале сентября уже тихо и красиво.

Как добраться

Летите или едете в Иркутск, дальше автобусом или на машине. До Листвянки около 70 км, до Ольхона около 270 км, до Чивыркуйского залива больше 400 км. Для Ольхона удобнее арендовать машину или взять место в маршрутке до Хужира.

Маршрут по дням

День 1. Иркутск. Прогулка по 130-му кварталу, набережная Ангары, вечером ужин с местной рыбой.

День 2. Листвянка. Байкальский музей, рынок с копчёным омулем, подъём на гору Черского или канатной дорогой на Камень Черского. Вечером можно сходить на закат к воде.

День 3. Дорога на Ольхон. По пути остановка в Тальцах (музей деревянного зодчества) и обед у переправы. Заселение в Хужире.

День 4. Ольхон. Мыс Бурхан со скалой Шаманка, мыс Хобой на севере, Песчаная бухта. Нужна экскурсия на УАЗе или своя машина с высокой посадкой.

День 5. Купание и отдых. Заливы Мухор и Загли подходят для спокойного дня. Можно взять катер или каяк.

